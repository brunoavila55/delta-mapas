"""Regenerate embedded WinAnsi font metrics. QA tooling requires fonttools only."""
from pathlib import Path
from fontTools.ttLib import TTFont
root = Path(__file__).resolve().parents[1]
output = ['// Generated by scripts/generate_pdf_font_metrics.py; embedded fonts use SIL OFL.']
for variant in ['Regular', 'Bold']:
    font = TTFont(root / 'src/assets/fonts' / f'LiberationSans-{variant}.ttf')
    units = font['head'].unitsPerEm
    cmap = font.getBestCmap()
    widths = []
    for code in range(32, 256):
        char = bytes([code]).decode('cp1252', errors='replace')
        glyph = cmap.get(ord(char), '.notdef')
        widths.append(font['hmtx'][glyph][0] * 1000 / units)
    prefix = variant.upper()
    output.append(f'pub const {prefix}_WIDTHS: [f32;224] = [' + ','.join(f'{v:.3f}' for v in widths) + '];')
    head, hhea, os2 = font['head'], font['hhea'], font['OS/2']
    values = [head.xMin, head.yMin, head.xMax, head.yMax, hhea.ascent, hhea.descent, os2.sCapHeight]
    output.append(f'pub const {prefix}_METRICS: [f32;7] = [' + ','.join(f'{v*1000/units:.3f}' for v in values) + '];')
(root / 'src/pdf_font_metrics.rs').write_text('\n'.join(output)+'\n')
